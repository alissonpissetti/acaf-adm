export function filterIconNames(query, categoryId = 'recommended') {
  const trimmed = String(query ?? '').trim().toLowerCase();

  if (trimmed) {
    return ALL_LUCIDE_ICON_NAMES.filter((name) => name.toLowerCase().includes(trimmed));
  }

  if (categoryId === 'all') {
    return ALL_LUCIDE_ICON_NAMES;
  }

  const category = ICON_CATEGORIES.find((item) => item.id === categoryId);
  return category?.icons ?? ICON_CATEGORIES[0].icons;
}

